import { describe, expect, it, vi } from 'vitest'
import { PlaybackController } from './playback'

describe('타임라인 재생 상태', () => {
  it('재생→tick→끝에서 자동 일시정지', () => {
    const p = new PlaybackController(4)
    p.play()
    expect(p.status).toBe('playing')
    p.tick(1)
    expect(p.progress).toBeCloseTo(0.25)
    p.tick(10)
    expect(p.progress).toBe(1)
    expect(p.status).toBe('paused')
  })
  it('일시정지 중에는 진행하지 않고, 끝에서 재생하면 처음부터', () => {
    const p = new PlaybackController(2)
    p.play()
    p.tick(1)
    p.pause()
    p.tick(1)
    expect(p.progress).toBeCloseTo(0.5)
    p.seek(1)
    p.play()
    expect(p.progress).toBe(0)
  })
  it('재시작, 탐색(seek)은 모션 미리보기, stop은 편집 모드', () => {
    const p = new PlaybackController(5)
    p.seek(0.6)
    expect(p.status).toBe('paused')
    expect(p.progress).toBeCloseTo(0.6)
    p.restart()
    expect(p).toMatchObject({ status: 'playing', progress: 0 })
    p.stop()
    expect(p.status).toBe('idle')
    p.seek(-3)
    expect(p.progress).toBe(0)
  })
  it('상태 구독은 상태 변화 때만, 진행률은 별도 리스너로 전달', () => {
    const p = new PlaybackController(1)
    const status = vi.fn()
    const progress = vi.fn()
    p.subscribe(status)
    p.onProgress(progress)
    p.play()
    for (let i = 0; i < 10; i++) p.tick(0.05)
    expect(status).toHaveBeenCalledTimes(1)
    expect(progress.mock.calls.length).toBeGreaterThanOrEqual(11)
  })
})
